"""Running a simulation spec: prepare AliSim's inputs, run AliSim, collect the truth.

`prepare` and `collect` are pure Python on a work directory; AliSim runs between them
in the pinned IQ-TREE container, from the argument lists in plan.json (also written as
NUL-separated `command<i>.args` files, so the pipeline's shell never parses them). The
golden datasets were generated by this code before it moved here from
`tests/golden/generate.py`, and must stay byte-identical (tests/golden/test_simulate.py).

Codon specs with `[model.site_classes]` simulate codeml's M3 model (dN/dS varying among
sites), which AliSim's mixtures cannot express: in IQ-TREE 3.1.3 a mixture component
cannot carry F3X4 frequencies, and every model is normalised to one substitution per
codon, so a high-dN/dS class would not evolve faster. Instead each codon site is drawn
into a class (probabilities p), each class is simulated in its own AliSim run on the
tree with branch lengths times that class's M3 rate, and the columns are interleaved
back: M3's own generative process.
"""

import hashlib
import json
import random
import re
import subprocess
import tempfile
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import dendropy

from phylobot.codons import CODONS, STANDARD
from phylobot.seqio import read_fasta, write_fasta
from phylobot.simulate import families
from phylobot.simulate.spec import FileRoot, FileTree, RandomRoot, RandomTree, Spec

OUTPUTS = ("input.fasta", "true_alignment.fasta", "true_ancestors.fasta", "true_tree.nwk")
SITE_CLASSES = "true_site_classes.tsv"
NAMES = "names.tsv"
PLAN = "plan.json"
TRANSITIONS = {frozenset("AG"), frozenset("CT")}
LEAF_LABEL = re.compile(r"(?<=[(,])([^(),:;]+)(?=[:,);])")  # a label right after ( or ,


@dataclass
class Plan:
    """What prepare decided, for AliSim and for collect."""

    seed: int
    commands: list[list[str]]
    root_name: str | None = None
    site_class: list[int] | None = None  # each codon site's class (site-class specs)
    rates: list[float] | None = None  # each class's relative rate

    def write(self, work: Path) -> None:
        (work / PLAN).write_text(json.dumps(asdict(self)) + "\n")
        for i, command in enumerate(self.commands):
            if command[0] != "iqtree3":
                raise ValueError("planned commands run iqtree3 only")
            (work / f"command{i}.args").write_text("".join(f"{arg}\0" for arg in command[1:]))

    @classmethod
    def read(cls, work: Path) -> Plan:
        return cls(**json.loads((work / PLAN).read_text()))


def write_newick(tree: dendropy.Tree) -> str:
    text: str = tree.as_string(
        schema="newick", suppress_rooting=True, unquoted_underscores=True
    ).strip()
    return text


def prepare_tree(spec: FileTree, path: Path) -> str:
    """Load the base tree, prune taxa, and root it at the outgroup branch midpoint (or at
    the tree's midpoint, with `midpoint = true`)."""
    tree = dendropy.Tree.get(path=path, schema="newick", preserve_underscores=True)
    if spec.prune:
        tree.prune_taxa_with_labels(list(spec.prune))
    if spec.outgroup:
        leaf = tree.find_node_with_taxon_label(spec.outgroup)
        if leaf is None:
            raise ValueError(f"outgroup {spec.outgroup!r} not in tree")
        tree.reroot_at_edge(
            leaf.edge,
            length1=leaf.edge.length / 2,
            length2=leaf.edge.length / 2,
            update_bipartitions=True,
        )
    elif spec.midpoint:
        tree.reroot_at_midpoint(update_bipartitions=True)
    tree.suppress_unifurcations()
    return write_newick(tree)


def gy_rate(omega: float, kappa: float, f3x4: list[float] | tuple[float, ...]) -> float:
    """Substitutions per unit time of an unnormalised GY+F3X4 matrix (standard code).

    f3x4 holds A, C, G, T frequencies for codon positions 1, 2, 3 (IQ-TREE's order).
    M3 scales every class by one factor, so each class's relative rate is its own
    unnormalised rate over the p-weighted mean of them all."""
    code = STANDARD.table
    freqs = [dict(zip("ACGT", f3x4[i : i + 4], strict=True)) for i in (0, 4, 8)]
    sense = [c for c in CODONS if code[c] != "*"]
    weight = {c: freqs[0][c[0]] * freqs[1][c[1]] * freqs[2][c[2]] for c in sense}
    total = sum(weight.values())
    pi = {c: w / total for c, w in weight.items()}
    rate = 0.0
    for i in sense:
        for j in sense:
            diff = [(a, b) for a, b in zip(i, j, strict=True) if a != b]
            if len(diff) != 1:
                continue
            q = pi[j] * (kappa if frozenset(diff[0]) in TRANSITIONS else 1.0)
            rate += pi[i] * q * (omega if code[i] != code[j] else 1.0)
    return rate


def alisim_command(prefix: str, tree: str, model: str, root: str, seed: int) -> list[str]:
    return [
        "iqtree3", "--alisim", prefix,
        "-t", tree,
        "-m", model,
        "--root-seq", root,
        "--write-all",
        "--out-format", "fasta",
        "--seed", str(seed),
    ]  # fmt: skip


def prepare(
    spec: Spec, seed: int, work: Path, tree_file: Path | None = None, root_file: Path | None = None
) -> Plan:
    """Write AliSim's inputs into `work` and plan its commands (also written there)."""
    if isinstance(spec.tree, FileTree):
        if tree_file is None:
            raise ValueError("this spec needs a tree file")
        tree = prepare_tree(spec.tree, tree_file)
        if spec.family is not None:
            # The file is the species tree; AliSim runs on the gene tree grown on it.
            families.write(families.grow(spec.family, tree, seed), work)
        else:
            (work / "tree.nwk").write_text(tree + "\n")
    root_name = None
    if isinstance(spec.root, FileRoot):
        if root_file is None:
            raise ValueError("this spec needs a root sequence file")
        root_name = spec.root.name
        sequences = read_fasta(root_file)
        if root_name not in sequences:
            raise ValueError(f"root sequence {root_name!r} not in {root_file.name}")
        write_fasta(work / "root.fasta", {root_name: sequences[root_name]})

    if spec.model.site_classes is not None:
        assert root_name is not None
        plan = _prepare_site_classes(spec, seed, work, root_name)
    else:
        plan = Plan(seed, [_command(spec, seed, root_name)], root_name)
    plan.write(work)
    return plan


def _command(spec: Spec, seed: int, root_name: str | None) -> list[str]:
    assert spec.model.substitution is not None
    if isinstance(spec.tree, RandomTree):
        tree, lengths = spec.tree.argument, [str(x) for x in spec.tree.lengths]
    else:
        tree, lengths = "tree.nwk", []
    command = alisim_command("sim", tree, spec.model.substitution, f"root.fasta,{root_name}", seed)
    if isinstance(spec.root, RandomRoot):
        # AliSim counts a codon sequence's length in nucleotides.
        length = spec.root.length * (3 if spec.model.codon else 1)
        command[7:9] = ["--length", str(length)]
    if lengths:
        command[5:5] = ["-rlen", *lengths]
        command.append("-redo")  # AliSim writes the random tree, then refuses to overwrite it
    if spec.model.seqtype:
        command[3:3] = ["-st", spec.model.seqtype]
    if spec.indels:
        command += ["--indel", spec.indels.rates, "--indel-size", spec.indels.sizes]
    return command


def _prepare_site_classes(spec: Spec, seed: int, work: Path, root_name: str) -> Plan:
    model, classes = spec.model, spec.model.site_classes
    assert classes is not None and model.kappa is not None and model.f3x4 is not None
    omegas, weights = classes.omegas, classes.proportions
    raw = [gy_rate(w, model.kappa, model.f3x4) for w in omegas]
    mean = sum(p * r for p, r in zip(weights, raw, strict=True))
    rates = [r / mean for r in raw]

    root = read_fasta(work / "root.fasta")[root_name]
    codons = [root[i : i + 3] for i in range(0, len(root), 3)]
    site_class = random.Random(seed).choices(range(len(omegas)), weights=weights, k=len(codons))
    if len(set(site_class)) != len(omegas):
        raise ValueError("a site class drew no sites; use a longer root sequence")

    base = dendropy.Tree.get(path=work / "tree.nwk", schema="newick", preserve_underscores=True)
    frequencies = "/".join(str(f) for f in model.f3x4)
    commands: list[list[str]] = []
    for k, (omega, rate) in enumerate(zip(omegas, rates, strict=True)):
        scaled = base.clone(depth=1)
        for edge in scaled.preorder_edge_iter():
            if edge.length is not None:
                edge.length *= rate
        (work / f"tree{k}.nwk").write_text(
            scaled.as_string(schema="newick", suppress_rooting=True, unquoted_underscores=True)
        )
        sites = [i for i, c in enumerate(site_class) if c == k]
        write_fasta(work / f"root{k}.fasta", {root_name: "".join(codons[i] for i in sites)})
        command = alisim_command(
            f"class{k}", f"tree{k}.nwk", f"GY{{{omega}/{model.kappa}}}+F3X4{{{frequencies}}}",
            f"root{k}.fasta,{root_name}", seed * 10 + k,
        )  # fmt: skip
        command[3:3] = ["-st", str(model.seqtype)]
        commands.append(command)
    return Plan(seed, commands, root_name, site_class, rates)


def clades(tree: dendropy.Tree) -> dict[frozenset[str], dendropy.Node]:
    """Each node keyed by the leaves below it (the trees share their rooting)."""
    return {
        frozenset(leaf.taxon.label for leaf in node.leaf_iter()): node
        for node in tree.preorder_node_iter()
    }


def _collect_site_classes(spec: Spec, plan: Plan, work: Path) -> tuple[dict[str, str], str, str]:
    """M3 by site classes (see the module docstring): the aligned sequences, the labelled
    tree (original branch lengths), and the site-class table."""
    classes = spec.model.site_classes
    assert classes is not None and plan.site_class is not None and plan.rates is not None
    assert plan.root_name is not None
    omegas, site_class, rates = classes.omegas, plan.site_class, plan.rates
    n_codons = len(read_fasta(work / "root.fasta")[plan.root_name]) // 3
    base = dendropy.Tree.get(path=work / "tree.nwk", schema="newick", preserve_underscores=True)
    columns: dict[str, dict[int, str]] = {}  # node name -> codon site -> codon
    labelled: dict[frozenset[str], str] | None = None
    for k in range(len(omegas)):
        sites = [i for i, c in enumerate(site_class) if c == k]
        sim = dendropy.Tree.get(
            path=work / f"class{k}.full.treefile", schema="newick", preserve_underscores=True
        )
        named = {leaves: node.label or node.taxon.label for leaves, node in clades(sim).items()}
        if labelled is None:
            labelled = named
        elif named != labelled:
            raise ValueError("site-class runs labelled the tree's nodes differently")
        for name, seq in read_fasta(work / f"class{k}.fa").items():
            for site, i in zip(sites, range(0, len(seq), 3), strict=True):
                columns.setdefault(name, {})[site] = seq[i : i + 3]

    assert labelled is not None
    aligned = {name: "".join(c[i] for i in range(n_codons)) for name, c in columns.items()}
    for leaves, node in clades(base).items():
        if node.taxon is None:
            node.label = labelled[leaves]
    tree = write_newick(base)
    table = "site\tclass\tomega\trate\n" + "".join(
        f"{i + 1}\t{k + 1}\t{omegas[k]}\t{rates[k]:.6f}\n" for i, k in enumerate(site_class)
    )
    return aligned, tree, table


def check_codons(sequences: dict[str, str]) -> None:
    for name, seq in sequences.items():
        if len(seq) % 3:
            raise ValueError(f"{name}: length {len(seq)} is not a whole number of codons")
        for i in range(0, len(seq), 3):
            if STANDARD.table.get(seq[i : i + 3]) == "*":
                raise ValueError(f"{name}: stop codon at codon {i // 3 + 1}")


def neutral_names(leaves: list[str]) -> dict[str, str]:
    """Original leaf name -> sim001, sim002, ... in the given order."""
    width = max(3, len(str(len(leaves))))
    return {name: f"sim{i:0{width}d}" for i, name in enumerate(leaves, 1)}


def collect(spec: Spec, plan: Plan, work: Path, out: Path, version: str, image: str) -> None:
    """Read AliSim's outputs in `work` into a truth bundle in `out`."""
    table = None
    if spec.model.site_classes is not None:
        aligned, tree_text, table = _collect_site_classes(spec, plan, work)
        command: list[str] | list[list[str]] = plan.commands
    else:
        aligned = read_fasta(work / "sim.fa")
        tree_text = (work / "sim.full.treefile").read_text().strip()
        command = plan.commands[0]

    tree = dendropy.Tree.get(data=tree_text, schema="newick", preserve_underscores=True)
    leaves = {leaf.taxon.label for leaf in tree.leaf_node_iter()}
    # Not AliSim's sim.unaligned.fa, which drops every "-" in the file, names included.
    unaligned = {name: seq.replace("-", "") for name, seq in aligned.items()}
    if spec.model.codon:
        check_codons(unaligned)

    renamed: dict[str, str] = {}
    if spec.names == "neutral":
        renamed = neutral_names([n for n in aligned if n in leaves])
        # In the text, so AliSim's branch lengths are kept exactly as written.
        tree_text = LEAF_LABEL.sub(lambda m: renamed[m.group(1)], tree_text)
    name = renamed.get

    out.mkdir(parents=True, exist_ok=True)
    write_fasta(out / "input.fasta", {name(n, n): unaligned[n] for n in aligned if n in leaves})
    write_fasta(
        out / "true_alignment.fasta", {name(n, n): s for n, s in aligned.items() if n in leaves}
    )
    write_fasta(out / "true_ancestors.fasta", {n: s for n, s in aligned.items() if n not in leaves})
    (out / "true_tree.nwk").write_text(tree_text + "\n")
    outputs: tuple[str, ...] = OUTPUTS
    if table is not None:
        (out / SITE_CLASSES).write_text(table)
        outputs += (SITE_CLASSES,)
    if renamed:
        (out / NAMES).write_text(
            "simulated\toriginal\n" + "".join(f"{s}\t{o}\n" for o, s in renamed.items())
        )
        outputs += (NAMES,)
    if spec.family is not None:
        for file in families.FILES:
            text = (work / file).read_text()
            if file == families.SPECIES and renamed:
                rows = [line.split("\t") for line in text.splitlines()[1:]]
                text = "gene\tspecies\n" + "".join(f"{name(g, g)}\t{s}\n" for g, s in rows)
            (out / file).write_text(text)
        outputs += families.FILES

    provenance: dict[str, Any] = {
        "iqtree_version": version,
        "image": image,
        "command": command,
        "seed": plan.seed,
        "sha256": {f: hashlib.sha256((out / f).read_bytes()).hexdigest() for f in outputs},
    }
    (out / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


def run_docker(work: Path, image: str, command: list[str]) -> None:
    docker = ["docker", "run", "--rm", "--platform", "linux/amd64"]
    docker += ["-v", f"{work}:/w", "-w", "/w", image]
    subprocess.run(docker + command, check=True, capture_output=True, text=True)


def iqtree_version(image: str) -> str:
    docker = ["docker", "run", "--rm", "--platform", "linux/amd64", image]
    result = subprocess.run(docker + ["iqtree3", "--version"], capture_output=True, text=True)
    return result.stdout.splitlines()[0]


def simulate_locally(
    spec: Spec,
    seed: int,
    out: Path,
    tree_file: Path | None = None,
    root_file: Path | None = None,
    image: str | None = None,
) -> None:
    """One replicate on this machine, AliSim in Docker (the golden generator's path)."""
    image = image or spec.image
    if image is None:
        raise ValueError("no IQ-TREE image: set simulation.image")
    with tempfile.TemporaryDirectory(prefix="alisim-") as tmp:
        work = Path(tmp)
        plan = prepare(spec, seed, work, tree_file, root_file)
        for command in plan.commands:
            run_docker(work, image, command)
        collect(spec, plan, work, out, iqtree_version(image), image)
